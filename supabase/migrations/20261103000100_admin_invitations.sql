-- VictoryCity M12: standard-administrator invitations.
--
-- Schema plus five SECURITY DEFINER RPCs. Deterministic under ordinary
-- `supabase db reset`. No row updates. No operator input. No bootstrap.
-- No guard activation. No application changes in this file.
--
-- WHY A TABLE
--   Invitations must be single-use, expirable, and revocable with enforcement
--   that survives concurrent requests and server restarts. Application memory
--   cannot do that, and `admin_users` cannot hold a "pending" state: inserting
--   a row for someone with no Auth account violates the user_id FK and would
--   wrongly grant is_admin() write access. Supabase Auth's invite email
--   creates the Auth user but records no expiry/revocation/consumption, so
--   this table is the authority and the RPCs below are the only writers.
--
-- TOKEN HANDLING
--   The plaintext token is generated by the application, emailed inside the
--   invitation link, and never stored. Only its SHA-256 hex digest is kept
--   here, so a database read never yields a usable invitation.
--
-- CONVENTIONS (matching M1/M1.1)
--   * `begin; ... commit;`, pinned `set search_path = ''`, stable error-code
--     prefixes mapped by the application (`ADMIN_INVITE_*`,
--     `ADMIN_DEACTIVATE_*`); errcode P0001 like the transfer RPC.
--   * No grants to anon/authenticated on the table; authenticated executes
--     the RPCs, and each RPC re-validates the caller (active primary) itself.
--   * Per-email and per-token advisory locks serialize concurrent
--     create/accept pairs the way the transfer RPC serializes seat moves.
--   * Invitations live 72 hours (`ADMIN_INVITE_TTL`), set by the database so
--     there is exactly one source for expiry.

begin;

-- 1. Invitation ledger -------------------------------------------------------
create table public.admin_invitations (
  id uuid primary key default gen_random_uuid(),
  email text not null
    check (email = lower(email))
    check (email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
  token_hash text not null unique
    check (token_hash ~ '^[0-9a-f]{64}$'),
  expires_at timestamptz not null,
  accepted_at timestamptz null,
  revoked_at timestamptz null,
  invited_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint admin_invitations_terminal_state_sane
    check (accepted_at is null or revoked_at is null),
  constraint admin_invitations_expiry_ordered
    check (expires_at > created_at)
);

create index admin_invitations_email_idx
  on public.admin_invitations (email, created_at desc);
create index admin_invitations_expires_at_idx
  on public.admin_invitations (expires_at)
  where accepted_at is null and revoked_at is null;

alter table public.admin_invitations enable row level security;

revoke all on public.admin_invitations from public, anon, authenticated;

-- 2. Create ------------------------------------------------------------------
-- Records one invitation for an email that is not already an administrator
-- and has no live invitation. The caller must be the active primary.
-- Expiry is stamped by the database: now() + 72 hours.
create or replace function public.create_admin_invitation(
  p_email text,
  p_token_hash text
)
returns table (
  invitation_id uuid,
  invitation_email text,
  invitation_expires_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_caller uuid;
  v_email text;
begin
  v_caller := (select auth.uid());
  if v_caller is null then
    raise exception 'ADMIN_INVITE_UNAUTHENTICATED: no authenticated user'
      using errcode = 'P0001';
  end if;

  if p_email is null or btrim(p_email) = '' then
    raise exception 'ADMIN_INVITE_INVALID_EMAIL: email is required'
      using errcode = 'P0001';
  end if;
  v_email := lower(btrim(p_email));
  if length(v_email) > 254
    or v_email !~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
  then
    raise exception 'ADMIN_INVITE_INVALID_EMAIL: email is not valid'
      using errcode = 'P0001';
  end if;

  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'ADMIN_INVITE_INVALID_TOKEN: token digest is not valid'
      using errcode = 'P0001';
  end if;

  -- Serialize concurrent creates for the same address.
  perform pg_advisory_xact_lock(hashtext('victorycity_admin_invite:' || v_email));

  if not exists (
    select 1
    from public.admin_users caller
    where caller.user_id = v_caller
      and caller.role = 'primary'
      and caller.is_active
  ) then
    raise exception 'ADMIN_INVITE_NOT_PRIMARY: caller is not the active primary'
      using errcode = 'P0001';
  end if;

  -- The address may already belong to an administrator (active or not).
  -- A deactivated administrator is re-enabled through reactivation, never
  -- through a second invitation, so any existing row blocks creation.
  perform 1
    from public.admin_users au
    join auth.users u on u.id = au.user_id
    where lower(u.email) = v_email;
  if found then
    raise exception 'ADMIN_INVITE_ALREADY_ADMIN: address is already an administrator'
      using errcode = 'P0001';
  end if;

  perform 1
    from public.admin_invitations ai
    where ai.email = v_email
      and ai.accepted_at is null
      and ai.revoked_at is null
      and ai.expires_at > now();
  if found then
    raise exception 'ADMIN_INVITE_ALREADY_PENDING: a live invitation already exists for this address'
      using errcode = 'P0001';
  end if;

  return query
    insert into public.admin_invitations
      (email, token_hash, expires_at, invited_by)
    values
      (v_email, p_token_hash, now() + interval '72 hours', v_caller)
    returning id, email, expires_at;
end
$fn$;

revoke all on function public.create_admin_invitation(text, text) from public, anon, authenticated;
grant execute on function public.create_admin_invitation(text, text) to authenticated;

-- 3. List --------------------------------------------------------------------
-- Pending and historical invitations for the primary's management screen.
-- Returns no rows for anyone who is not the active primary (same convention
-- as list_primary_transfer_candidates: empty, not an error).
create or replace function public.list_admin_invitations()
returns table (
  invitation_id uuid,
  invitation_email text,
  invitation_expires_at timestamptz,
  invitation_accepted_at timestamptz,
  invitation_revoked_at timestamptz,
  invitation_created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $fn$
  select
    ai.id,
    ai.email,
    ai.expires_at,
    ai.accepted_at,
    ai.revoked_at,
    ai.created_at
  from public.admin_invitations ai
  where exists (
    select 1
    from public.admin_users caller
    where caller.user_id = (select auth.uid())
      and caller.role = 'primary'
      and caller.is_active
  )
  order by ai.created_at desc, ai.id;
$fn$;

revoke all on function public.list_admin_invitations() from public, anon, authenticated;
grant execute on function public.list_admin_invitations() to authenticated;

-- 4. Revoke ------------------------------------------------------------------
-- Cancels a pending invitation. Idempotent: revoking an already-revoked
-- invitation succeeds. A consumed invitation can never be revoked.
create or replace function public.revoke_admin_invitation(
  p_invitation_id uuid
)
returns table (
  invitation_id uuid,
  invitation_revoked_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_caller uuid;
  v_row public.admin_invitations%rowtype;
begin
  v_caller := (select auth.uid());
  if v_caller is null then
    raise exception 'ADMIN_INVITE_UNAUTHENTICATED: no authenticated user'
      using errcode = 'P0001';
  end if;

  if p_invitation_id is null then
    raise exception 'ADMIN_INVITE_NOT_FOUND: invitation does not exist'
      using errcode = 'P0001';
  end if;

  if not exists (
    select 1
    from public.admin_users caller
    where caller.user_id = v_caller
      and caller.role = 'primary'
      and caller.is_active
  ) then
    raise exception 'ADMIN_INVITE_NOT_PRIMARY: caller is not the active primary'
      using errcode = 'P0001';
  end if;

  select *
    into v_row
    from public.admin_invitations ai
    where ai.id = p_invitation_id
    for update;

  if not found then
    raise exception 'ADMIN_INVITE_NOT_FOUND: invitation does not exist'
      using errcode = 'P0001';
  end if;

  if v_row.accepted_at is not null then
    raise exception 'ADMIN_INVITE_ALREADY_ACCEPTED: invitation was already used'
      using errcode = 'P0001';
  end if;

  update public.admin_invitations
    set revoked_at = coalesce(revoked_at, now())
    where id = p_invitation_id
    returning id, revoked_at
    into invitation_id, invitation_revoked_at;

  return next;
end
$fn$;

revoke all on function public.revoke_admin_invitation(uuid) from public, anon, authenticated;
grant execute on function public.revoke_admin_invitation(uuid) to authenticated;

-- 5. Accept ------------------------------------------------------------------
-- Consumes one invitation and enrols the CALLER as an active standard
-- administrator, atomically. Single-use is enforced by the transaction: the
-- row is locked, re-checked, and stamped before the admin row is written, so
-- two concurrent accepts serialize and the loser sees ALREADY_ACCEPTED.
-- The invited email is informational; enrolment always targets auth.uid(),
-- so a token forwarded to someone else cannot enrol a stranger as the
-- original address — the row records who actually accepted via invited_by
-- audit on admin_users.created_by.
create or replace function public.accept_admin_invitation(
  p_token_hash text
)
returns table (
  admin_user_id uuid
)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_caller uuid;
  v_row public.admin_invitations%rowtype;
begin
  v_caller := (select auth.uid());
  if v_caller is null then
    raise exception 'ADMIN_INVITE_UNAUTHENTICATED: no authenticated user'
      using errcode = 'P0001';
  end if;

  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'ADMIN_INVITE_INVALID: invitation is not valid'
      using errcode = 'P0001';
  end if;

  -- Serialize concurrent accepts of the same token.
  perform pg_advisory_xact_lock(hashtext('victorycity_admin_invite_accept:' || p_token_hash));

  select *
    into v_row
    from public.admin_invitations ai
    where ai.token_hash = p_token_hash
    for update;

  if not found then
    raise exception 'ADMIN_INVITE_INVALID: invitation is not valid'
      using errcode = 'P0001';
  end if;

  if v_row.revoked_at is not null then
    raise exception 'ADMIN_INVITE_REVOKED: invitation was revoked'
      using errcode = 'P0001';
  end if;

  if v_row.accepted_at is not null then
    raise exception 'ADMIN_INVITE_ALREADY_ACCEPTED: invitation was already used'
      using errcode = 'P0001';
  end if;

  if v_row.expires_at <= now() then
    raise exception 'ADMIN_INVITE_EXPIRED: invitation has expired'
      using errcode = 'P0001';
  end if;

  -- The invitation is addressed to one email. Enforce the match inside the
  -- same transaction so a token forwarded to someone else cannot enrol a
  -- stranger: the accepting Auth account must own the invited address.
  declare
    v_caller_email text;
  begin
    select lower(u.email) into v_caller_email
      from auth.users u
      where u.id = v_caller;
  end;
if v_caller_email is distinct from v_row.email then
    raise exception 'ADMIN_INVITE_EMAIL_MISMATCH: invitation was sent to a different address'
      using errcode = 'P0001';
  end if;

  if exists (
    select 1
    from public.admin_users au
    where au.user_id = v_caller
  ) then
    raise exception 'ADMIN_INVITE_ALREADY_ADMIN: account is already an administrator'
      using errcode = 'P0001';
  end if;

  insert into public.admin_users (user_id, role, is_active, created_by)
  values (v_caller, 'standard', true, v_row.invited_by);

  update public.admin_invitations
    set accepted_at = now()
    where id = v_row.id;

  admin_user_id := v_caller;
  return next;
end
$fn$;

revoke all on function public.accept_admin_invitation(text) from public, anon, authenticated;
grant execute on function public.accept_admin_invitation(text) to authenticated;

-- 6. List standard administrators --------------------------------------------
-- Every standard administrator with their active state, for the primary's
-- management screen. Primary-only, empty (not an error) for anyone else.
create or replace function public.list_standard_admins()
returns table (
  admin_user_id uuid,
  admin_email text,
  admin_is_active boolean,
  admin_since timestamptz
)
language sql
stable
security definer
set search_path = ''
as $fn$
  select
    au.user_id,
    u.email::text as email,
    au.is_active,
    au.created_at as admin_since
  from public.admin_users au
  join auth.users u on u.id = au.user_id
  where au.role = 'standard'
    and exists (
      select 1
      from public.admin_users caller
      where caller.user_id = (select auth.uid())
        and caller.role = 'primary'
        and caller.is_active
    )
  order by au.is_active desc, au.created_at, au.user_id;
$fn$;

revoke all on function public.list_standard_admins() from public, anon, authenticated;
grant execute on function public.list_standard_admins() to authenticated;

-- 7. Deactivate --------------------------------------------------------------
-- Deactivates one active standard administrator. The primary seat is never
-- touched: self-deactivation and primary targets are rejected, so the
-- at-most-one and must-retain-primary invariants cannot be disturbed here.
-- The target row is locked before the write, serializing against a
-- concurrent primary transfer to the same account.
create or replace function public.deactivate_standard_admin(
  p_target_user_id uuid
)
returns table (
  admin_user_id uuid,
  admin_is_active boolean
)
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_caller uuid;
  v_target_role text;
  v_target_active boolean;
begin
  v_caller := (select auth.uid());
  if v_caller is null then
    raise exception 'ADMIN_DEACTIVATE_UNAUTHENTICATED: no authenticated user'
      using errcode = 'P0001';
  end if;

  if p_target_user_id is null then
    raise exception 'ADMIN_DEACTIVATE_INVALID_TARGET: target is required'
      using errcode = 'P0001';
  end if;

  if not exists (
    select 1
    from public.admin_users caller
    where caller.user_id = v_caller
      and caller.role = 'primary'
      and caller.is_active
  ) then
    raise exception 'ADMIN_DEACTIVATE_NOT_PRIMARY: caller is not the active primary'
      using errcode = 'P0001';
  end if;

  if p_target_user_id = v_caller then
    raise exception 'ADMIN_DEACTIVATE_SELF: cannot deactivate your own account'
      using errcode = 'P0001';
  end if;

  select au.role, au.is_active
    into v_target_role, v_target_active
    from public.admin_users au
    where au.user_id = p_target_user_id
    for update;

  if not found then
    raise exception 'ADMIN_DEACTIVATE_TARGET_NOT_ADMIN: target is not an administrator'
      using errcode = 'P0001';
  end if;

  if v_target_role <> 'standard' then
    raise exception 'ADMIN_DEACTIVATE_TARGET_NOT_STANDARD: only standard administrators can be deactivated here'
      using errcode = 'P0001';
  end if;

  if not v_target_active then
    raise exception 'ADMIN_DEACTIVATE_TARGET_INACTIVE: administrator is already deactivated'
      using errcode = 'P0001';
  end if;

  update public.admin_users
    set is_active = false,
        deactivated_at = now(),
        deactivated_by = v_caller
    where user_id = p_target_user_id
    returning user_id, is_active
    into admin_user_id, admin_is_active;

  return next;
end
$fn$;

revoke all on function public.deactivate_standard_admin(uuid) from public, anon, authenticated;
grant execute on function public.deactivate_standard_admin(uuid) to authenticated;

commit;
